CREATE TABLE TRANSLATION
(
    TRANSLATION_GROUP   VARCHAR(50)  NOT NULL,
    TRANSLATION_TYPE    VARCHAR(50)  NOT NULL,
    TRANSLATION_CODE    VARCHAR(50)  NOT NULL,
    TRANSLATION_LOCALE  VARCHAR(2)   NOT NULL DEFAULT 'en',
    TRANSLATION_CONTENT VARCHAR(255) NOT NULL,
    DATA_STATUS         VARCHAR(10)  NOT NULL DEFAULT 'ENABLED',
    CREATED_BY          VARCHAR(50)  NOT NULL DEFAULT 'system',
    CREATED_AT          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY          VARCHAR(50)  NOT NULL DEFAULT 'system',
    UPDATED_AT          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT TB_TRANSLATION_PK PRIMARY KEY (TRANSLATION_GROUP, TRANSLATION_TYPE, TRANSLATION_CODE, TRANSLATION_LOCALE)
)