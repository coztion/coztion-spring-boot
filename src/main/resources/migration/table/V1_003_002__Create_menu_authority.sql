CREATE TABLE TB_MENU_AUTHORITY
(
    MENU_ID       VARCHAR(50) NOT NULL,
    AUTHORITY_CODE VARCHAR(50) NOT NULL,
    CONSTRAINT TB_MENU_AUTHORITY_PK UNIQUE KEY (MENU_ID, AUTHORITY_CODE),
    CONSTRAINT TB_MENU_AUTHORITY_MENU_ID_FK FOREIGN KEY (MENU_ID) REFERENCES TB_MENU (MENU_ID)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT TB_MENU_AUTHORITY_AUTHORITY_CODE_FK FOREIGN KEY (AUTHORITY_CODE) REFERENCES TB_AUTHORITY (AUTHORITY_CODE)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);