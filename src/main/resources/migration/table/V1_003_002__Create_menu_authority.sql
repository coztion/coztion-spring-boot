CREATE TABLE TB_MENU_AUTHORITY
(
    MENU_ID       VARCHAR(50) NOT NULL,
    AUTHORITY_ROLE VARCHAR(50) NOT NULL,
    AUTHORITY_TYPE VARCHAR(10) NOT NULL,
    CONSTRAINT TB_MENU_AUTHORITY_PK UNIQUE KEY (MENU_ID, AUTHORITY_ROLE, AUTHORITY_TYPE),
    CONSTRAINT TB_MENU_AUTHORITY_MENU_ID_FK FOREIGN KEY (MENU_ID) REFERENCES TB_MENU (MENU_ID)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT TB_MENU_AUTHORITY_AUTHORITY_ROLE_FK FOREIGN KEY (AUTHORITY_ROLE) REFERENCES TB_AUTHORITY (AUTHORITY_ROLE)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);