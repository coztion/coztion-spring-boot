CREATE TABLE FILE
(
    FILE_ID           VARCHAR(36)  NOT NULL,
    FILE_GROUP_ID     VARCHAR(36)  NOT NULL,
    FILE_NAME         VARCHAR(255) NOT NULL,
    FILE_EXTENSION    VARCHAR(20)  NOT NULL DEFAULT '',
    FILE_CONTENT_TYPE VARCHAR(100) NOT NULL,
    FILE_SIZE         BIGINT       NOT NULL,
    FILE_PATH         VARCHAR(500) NOT NULL,
    DATA_STATUS       VARCHAR(10)  NOT NULL DEFAULT 'ENABLED',
    CREATED_BY        VARCHAR(50)  NOT NULL DEFAULT 'system',
    CREATED_AT        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY        VARCHAR(50)  NOT NULL DEFAULT 'system',
    UPDATED_AT        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT TB_FILE_PK PRIMARY KEY (FILE_ID),
    INDEX TB_FILE_IDX_01 (FILE_GROUP_ID)
)
