CREATE TABLE TB_COMMON_CODE
(
    GROUP_CODE       VARCHAR(50)  NOT NULL,
    COMMON_CODE      VARCHAR(50)  NOT NULL,
    COMMON_CODE_NAME VARCHAR(100) NOT NULL,
    COMMON_CODE_DESC VARCHAR(255),
    COMMON_CODE_OPTION_1 VARCHAR(255),
    COMMON_CODE_OPTION_2 VARCHAR(255),
    COMMON_CODE_OPTION_3 VARCHAR(255),
    COMMON_CODE_OPTION_4 VARCHAR(255),
    COMMON_CODE_OPTION_5 VARCHAR(255),
    DATA_STATUS      VARCHAR(10)  NOT NULL DEFAULT 'ENABLE',
    SORT_ORDER       BIGINT       NOT NULL,
    CREATED_BY       VARCHAR(50)  NOT NULL DEFAULT 'system',
    CREATED_AT       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY       VARCHAR(50)  NOT NULL DEFAULT 'system',
    UPDATED_AT       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT TB_COMMON_CODE_PK PRIMARY KEY (GROUP_CODE, COMMON_CODE),
    CONSTRAINT TB_COMMON_CODE_FK FOREIGN KEY (GROUP_CODE) REFERENCES TB_GROUP_CODE (GROUP_CODE)
        ON UPDATE CASCADE
        ON DELETE CASCADE
)
