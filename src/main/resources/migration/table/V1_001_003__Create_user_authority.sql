CREATE TABLE TB_USER_AUTHORITY
(
    USERNAME       VARCHAR(50) NOT NULL,
    AUTHORITY_ROLE VARCHAR(50) NOT NULL,
    CONSTRAINT TB_USER_AUTHORITY_PK UNIQUE KEY (USERNAME, AUTHORITY_ROLE),
    CONSTRAINT TB_USER_AUTHORITY_USERNAME_FK FOREIGN KEY (USERNAME) REFERENCES TB_USER (USERNAME)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT TB_USER_AUTHORITY_AUTHORITY_ROLE_FK FOREIGN KEY (AUTHORITY_ROLE) REFERENCES TB_AUTHORITY (AUTHORITY_ROLE)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);