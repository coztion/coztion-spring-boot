CREATE TABLE TB_ROLE_PERMISSION
(
    ROLE_CODE       VARCHAR(50) NOT NULL,
    PERMISSION_CODE VARCHAR(50) NOT NULL,
    CONSTRAINT TB_ROLE_PERMISSION_PK PRIMARY KEY (ROLE_CODE, PERMISSION_CODE),
    CONSTRAINT TB_ROLE_PERMISSION_ROLE_CODE_FK FOREIGN KEY (ROLE_CODE) REFERENCES TB_ROLE (ROLE_CODE)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT TB_ROLE_PERMISSION_PERMISSION_CODE_FK FOREIGN KEY (PERMISSION_CODE) REFERENCES TB_PERMISSION (PERMISSION_CODE)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);
